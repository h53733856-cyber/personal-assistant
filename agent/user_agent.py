"""
用户主动请求的分析。

把用户的一句话请求转换成与邮件分析同构的分析结果，
这样用户入口与邮件入口创建的任务可以使用同一套处理流程。
"""

from agent.llm import ask_llm_json


def analyze_user_request(text):
    """分析用户直接提出的请求，返回 JSON 字典（与邮件分析同构）。"""

    prompt = f"""
你是我的个人助手。

用户直接向你提出了下面的请求：

{text}

请判断用户是否要求你完成某个具体操作。

注意：
1. 只有用户明确要求完成某个具体操作时，need_action 才为 true。
2. 普通的聊天、提问、咨询，如果没有要求完成具体操作，则 need_action 为 false。
3. 如果涉及需要办理的事务，type 请使用具体事务名，例如：
   - 宿舍报修
   - 发送邮件
   - 提交申请
   - 事务办理
4. 只能使用用户请求中明确出现的信息，不要自行编造。
5. 如果不存在某项信息，使用 null。
6. 如果用户要求办理的事务可能产生实际后果（提交表单、发送邮件、
   退课、取消申请、删除数据等），action 中要写明需要执行的具体操作。
7. 提醒类请求（例如"提醒我明天交作业"、"明天晚上交作业"、
   "别忘了开会"）以及用户提出的待办事项，即使没有出现"提醒我"
   字样，也属于需要行动：need_action 为 true，type 使用"提醒事项"，
   action 写明要提醒的时间和内容。
8. 用户提出一个待办事项时，不要把它当作普通的陈述句拒绝建任务。

必须严格按照下面的 JSON 格式返回：

{{
    "type": "请求类型",
    "core": "用一句话概括用户想做的事",
    "time": "重要时间，没有则为 null",
    "deadline": "截止时间，没有则为 null",
    "need_action": true,
    "action": "需要完成的具体操作，没有则为 null"
}}

只返回 JSON，不要添加 Markdown，不要添加解释。
"""

    return ask_llm_json(prompt)
